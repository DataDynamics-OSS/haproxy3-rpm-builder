#!/bin/bash
#
# 내부 저장소의 현재 상태를 공개 저장소로 배포합니다.
#
#   ./publish.sh                  소스만 배포
#   ./publish.sh --with-releases  릴리스(RPM)까지 함께 배포
#   ./publish.sh --dry-run        무엇이 바뀌는지만 보여주고 아무것도 올리지 않음
#
# 배포되는 내용
#   - 현재 브랜치의 전체 커밋 이력 (원 저장소 작성자 표기 보존)
#   - 그 위에 저장소 URL 을 공개 저장소로 바꾼 커밋 하나
#
# 내부 저장소의 문서는 내부 URL 을 그대로 유지합니다. URL 치환은 배포용
# 커밋에서만 일어나므로, 두 저장소의 이력은 마지막 커밋 하나만 달라집니다.
#
set -euo pipefail

INTERNAL_SLUG="${INTERNAL_SLUG:-DataDynamics/haproxy3-rpm-builder-internal}"
PUBLIC_SLUG="${PUBLIC_SLUG:-DataDynamics-OSS/haproxy3-rpm-builder}"
PUBLIC_URL="https://github.com/${PUBLIC_SLUG}.git"
BRANCH="${BRANCH:-main}"

WITH_RELEASES=0
DRY_RUN=0
for arg in "$@"; do
    case "$arg" in
        --with-releases) WITH_RELEASES=1 ;;
        --dry-run)       DRY_RUN=1 ;;
        -h|--help)       sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "알 수 없는 옵션: $arg" >&2; exit 2 ;;
    esac
done

say() { printf '\n==> %s\n' "$*"; }
run() { if [ "$DRY_RUN" = 1 ]; then echo "    [dry-run] $*"; else "$@"; fi; }

# --- 사전 점검 ------------------------------------------------------------
cd "$(dirname "$0")"

command -v gh >/dev/null || { echo "gh CLI 가 필요합니다." >&2; exit 1; }
gh auth status >/dev/null 2>&1 || { echo "gh 인증이 필요합니다: gh auth login" >&2; exit 1; }

if [ -n "$(git status --porcelain)" ]; then
    echo "작업 트리에 커밋되지 않은 변경이 있습니다. 정리한 뒤 다시 실행하세요." >&2
    git status --short >&2
    exit 1
fi

SRC_COMMIT=$(git rev-parse --short HEAD)
say "배포 대상: $INTERNAL_SLUG@$SRC_COMMIT -> $PUBLIC_SLUG"

# --- 배포용 커밋 준비 -----------------------------------------------------
# 임시 워크트리에서 작업하므로 현재 체크아웃에는 영향이 없습니다.
WORKTREE=$(mktemp -d)
TMPBRANCH="publish-tmp-$$"
cleanup() {
    git worktree remove --force "$WORKTREE" 2>/dev/null || true
    git branch -D "$TMPBRANCH" 2>/dev/null || true
}
trap cleanup EXIT

git worktree add -q --detach "$WORKTREE" HEAD
git -C "$WORKTREE" switch -q -c "$TMPBRANCH"

say "저장소 URL 치환"
# 전체 경로를 먼저 바꾼 뒤, 남은 저장소 이름만 바꿉니다 (순서 중요).
mapfile -t TARGETS < <(cd "$WORKTREE" && grep -rl 'haproxy3-rpm-builder-internal' \
    --include='*.md' --include='*.spec' --include='*.sh' --include='Makefile' . 2>/dev/null || true)

if [ ${#TARGETS[@]} -eq 0 ]; then
    echo "    치환할 대상이 없습니다."
else
    for f in "${TARGETS[@]}"; do
        [ "$(basename "$f")" = "publish.sh" ] && continue
        sed -i -e "s#${INTERNAL_SLUG}#${PUBLIC_SLUG}#g" \
               -e "s#haproxy3-rpm-builder-internal#haproxy3-rpm-builder#g" "$WORKTREE/$f"
        echo "    $f"
    done
fi

# publish.sh 는 내부 전용 도구이므로 공개본에서 제외합니다.
git -C "$WORKTREE" rm -q --cached publish.sh >/dev/null 2>&1 || true
rm -f "$WORKTREE/publish.sh"

if [ -n "$(git -C "$WORKTREE" status --porcelain)" ]; then
    git -C "$WORKTREE" add -A
    git -C "$WORKTREE" commit -q -m "Point documentation at the public repository

Generated by publish.sh from ${INTERNAL_SLUG}@${SRC_COMMIT}. Repository
URLs are rewritten here rather than in the source repository so the two
histories differ only in this final commit."
    echo "    배포용 커밋: $(git -C "$WORKTREE" rev-parse --short HEAD)"
fi

# --- push -----------------------------------------------------------------
say "공개 저장소로 push ($BRANCH)"
# 공개 저장소의 초기 커밋과는 이력이 무관하므로 강제 갱신합니다.
if [ "$DRY_RUN" = 1 ]; then
    echo "    [dry-run] git push --force $PUBLIC_URL $TMPBRANCH:$BRANCH"
    git -C "$WORKTREE" log --oneline -3
else
    git -C "$WORKTREE" push --force -q "$PUBLIC_URL" "$TMPBRANCH:$BRANCH"
    echo "    https://github.com/$PUBLIC_SLUG"
fi

# --- 릴리스 미러링 --------------------------------------------------------
if [ "$WITH_RELEASES" = 1 ]; then
    say "릴리스 미러링"
    TAGS=$(gh release list --repo "$INTERNAL_SLUG" --json tagName --jq '.[].tagName' | sort -V)
    [ -z "$TAGS" ] && echo "    내부 저장소에 릴리스가 없습니다."

    for tag in $TAGS; do
        if gh release view "$tag" --repo "$PUBLIC_SLUG" >/dev/null 2>&1; then
            echo "    $tag 이미 존재 — 건너뜀"
            continue
        fi
        meta=$(gh release view "$tag" --repo "$INTERNAL_SLUG" --json name,body,isLatest)
        title=$(jq -r .name <<<"$meta")
        latest=$(jq -r .isLatest <<<"$meta")
        assets=$(mktemp -d)

        jq -r .body <<<"$meta" \
            | sed -e "s#${INTERNAL_SLUG}#${PUBLIC_SLUG}#g" \
                  -e "s#haproxy3-rpm-builder-internal#haproxy3-rpm-builder#g" > "$assets/notes.md"

        echo "    $tag 자산 내려받는 중..."
        gh release download "$tag" --repo "$INTERNAL_SLUG" -D "$assets" >/dev/null

        flag="--latest=false"; [ "$latest" = "true" ] && flag="--latest"
        if [ "$DRY_RUN" = 1 ]; then
            echo "    [dry-run] gh release create $tag ($(ls "$assets"/*.rpm 2>/dev/null | wc -l) assets) $flag"
        else
            gh release create "$tag" "$assets"/*.rpm \
                --repo "$PUBLIC_SLUG" --title "$title" \
                --notes-file "$assets/notes.md" $flag >/dev/null
            echo "    $tag 완료 ($(ls "$assets"/*.rpm | wc -l) assets)"
        fi
        rm -rf "$assets"
    done
fi

say "완료"
[ "$DRY_RUN" = 1 ] && echo "    (dry-run 이었으므로 실제로는 아무것도 올리지 않았습니다)"
exit 0
